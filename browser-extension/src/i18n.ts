export const messages = { "zh-CN": zh, en } as const;
export type MessageKey = keyof typeof zh;

export function localeFromLanguage(language: string): UiLocale {
  return language.toLocaleLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: UiLocale, key: MessageKey, params: Record<string, string | number> = {}): string {
  return Object.entries(params).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    messages[locale][key],
  );
}
